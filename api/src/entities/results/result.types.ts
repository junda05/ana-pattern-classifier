/**
 * Types and enums for the results module
 *
 * Definitions:
 *
 * ResultStatus - Possible states of a result:
 * - PENDING: Awaiting review
 * - CORRECTED: Corrected
 * - VERIFIED: Verified
 *
 * PredictionClass - ICAP prediction classes (every specific class):
 * - General level: NEGATIVE, NUCLEAR, CYTOPLASMIC, MITOTIC
 * - Competent level, nuclear: NUCLEAR_HOMOGENEOUS, NUCLEAR_DENSE_FINE_SPECKLED, NUCLEAR_CENTROMERE, NUCLEAR_SPECKLED, NUCLEOLAR
 * - Competent level, cytoplasmic: CYTOPLASMIC_FIBRILLAR, CYTOPLASMIC_DISCRETE_DOTS, CYTOPLASMIC_SPECKLED, CYTOPLASMIC_RETICULAR_AMA, CYTOPLASMIC_POLAR_GOLGI
 * - Expert level, nucleolar: NUCLEOLAR_HOMOGENEOUS, NUCLEOLAR_CLUMPY, NUCLEOLAR_PUNCTATE
 * - Expert level, cytoplasmic speckled: CYTOPLASMIC_DENSE_FINE_SPECKLED, CYTOPLASMIC_FINE_SPECKLED
 * - Expert level, mitotic: MITOTIC_CENTROSOME, MITOTIC_SPINDLE_FIBERS, MITOTIC_NUMA, MITOTIC_INTERCELLULAR_BRIDGE, MITOTIC_CHROMOSOMAL_ENVELOPE
 */

export enum ResultStatus {
  PENDING = 'PENDING',
  CORRECTED = 'CORRECTED',
  VERIFIED = 'VERIFIED',
}

export enum PredictionClass {
  // General level
  NEGATIVE = 'NEGATIVE',
  NUCLEAR = 'NUCLEAR',
  CYTOPLASMIC = 'CYTOPLASMIC',
  MITOTIC = 'MITOTIC',

  // Competent level - nuclear
  NUCLEAR_HOMOGENEOUS = 'NUCLEAR_HOMOGENEOUS',
  NUCLEAR_DENSE_FINE_SPECKLED = 'NUCLEAR_DENSE_FINE_SPECKLED',
  NUCLEAR_CENTROMERE = 'NUCLEAR_CENTROMERE',
  NUCLEAR_SPECKLED = 'NUCLEAR_SPECKLED',
  NUCLEOLAR = 'NUCLEOLAR',

  // Competent level - cytoplasmic
  CYTOPLASMIC_FIBRILLAR = 'CYTOPLASMIC_FIBRILLAR',
  CYTOPLASMIC_DISCRETE_DOTS = 'CYTOPLASMIC_DISCRETE_DOTS',
  CYTOPLASMIC_SPECKLED = 'CYTOPLASMIC_SPECKLED',
  CYTOPLASMIC_RETICULAR_AMA = 'CYTOPLASMIC_RETICULAR_AMA',
  CYTOPLASMIC_POLAR_GOLGI = 'CYTOPLASMIC_POLAR_GOLGI',

  // Expert level - nucleolar
  NUCLEOLAR_HOMOGENEOUS = 'NUCLEOLAR_HOMOGENEOUS',
  NUCLEOLAR_CLUMPY = 'NUCLEOLAR_CLUMPY',
  NUCLEOLAR_PUNCTATE = 'NUCLEOLAR_PUNCTATE',

  // Expert level - cytoplasmic speckled
  CYTOPLASMIC_DENSE_FINE_SPECKLED = 'CYTOPLASMIC_DENSE_FINE_SPECKLED',
  CYTOPLASMIC_FINE_SPECKLED = 'CYTOPLASMIC_FINE_SPECKLED',

  // Expert level - mitotic
  MITOTIC_CENTROSOME = 'MITOTIC_CENTROSOME',
  MITOTIC_SPINDLE_FIBERS = 'MITOTIC_SPINDLE_FIBERS',
  MITOTIC_NUMA = 'MITOTIC_NUMA',
  MITOTIC_INTERCELLULAR_BRIDGE = 'MITOTIC_INTERCELLULAR_BRIDGE',
  MITOTIC_CHROMOSOMAL_ENVELOPE = 'MITOTIC_CHROMOSOMAL_ENVELOPE',
}
