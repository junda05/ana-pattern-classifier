/**
 * Shared TypeORM DataSource configuration
 *
 * Used by:
 * - The TypeORM CLI (generating/running/reverting migrations)
 * - The NestJS runtime (through database.providers.ts)
 * - The migration runner of the container (npm run migration:run:prod)
 *
 * Keeps a single source of truth for the database configuration.
 *
 * Schema changes go through migrations only: `synchronize` is off in every
 * environment and migrations never run implicitly on connect. The paths are
 * relative to this file, so the same configuration works from `src/` (ts-node,
 * TypeORM CLI) and from `dist/` (compiled .js; TypeORM skips .d.ts files).
 *
 * Connection settings come from the environment (DB_HOST, DB_PORT, DB_USERNAME,
 * DB_PASSWORD, DB_NAME); a local .env file is read if present and never
 * overrides variables that are already set.
 *
 * Transport encryption: DB_ENCRYPT (default false) and
 * DB_TRUST_SERVER_CERTIFICATE (default true) suit the private Compose
 * network. In production set DB_ENCRYPT=true and
 * DB_TRUST_SERVER_CERTIFICATE=false, with a certificate the client trusts
 * installed on SQL Server.
 */

import { DataSource } from 'typeorm';
import { config } from 'dotenv';
import { join } from 'path';

config();

const DEFAULT_SQL_SERVER_PORT = 1433;

/** Boolean environment variable: true/false, 1/0 or yes/no; empty or unset gives the fallback. */
function booleanEnv(name: string, fallback: boolean): boolean {
  const value = process.env[name]?.trim().toLowerCase();
  if (!value) {
    return fallback;
  }
  if (['true', '1', 'yes'].includes(value)) {
    return true;
  }
  if (['false', '0', 'no'].includes(value)) {
    return false;
  }
  throw new Error(
    `${name} must be true or false (got "${process.env[name]}").`,
  );
}

export const AppDataSource = new DataSource({
  type: 'mssql',
  host: process.env.DB_HOST!,
  port: Number(process.env.DB_PORT) || DEFAULT_SQL_SERVER_PORT,
  username: process.env.DB_USERNAME!,
  password: process.env.DB_PASSWORD!,
  database: process.env.DB_NAME!,
  entities: [
    join(__dirname, '..', '**', '*.entity{.ts,.js}'),
    join(__dirname, '..', '..', 'entities', '**', '*.entity{.ts,.js}'),
  ],
  migrations: [join(__dirname, 'migrations', '*{.ts,.js}')],
  synchronize: false,
  migrationsRun: false,
  logging: ['error', 'warn', 'migration'],
  options: {
    encrypt: booleanEnv('DB_ENCRYPT', false),
    trustServerCertificate: booleanEnv('DB_TRUST_SERVER_CERTIFICATE', true),
    // Store UTC: the driver reads and writes DATETIME values as UTC, and the
    // creation timestamps generated by the database use SYSUTCDATETIME() (see the
    // entities). Clients format dates in their own timezone; APP_TIMEZONE (main.ts)
    // only affects how the server process itself formats dates.
    useUTC: true,
  },
});
