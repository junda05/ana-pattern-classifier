/**
 * Main service for managing results
 *
 * Main features:
 * - Reading results with role-based restrictions
 * - Creating results with multiple predictions and files
 * - Updating results (status and observations only)
 * - Managing result corrections
 * - Result statistics for the analytics dashboard
 *
 * Business rules:
 * - STANDARD users view/modify their own results plus the shared PENDING queue
 *   (every PENDING result is visible to everyone so it can be verified)
 * - STANDARD users cannot correct a VERIFIED result; ADMIN users can
 * - ADMIN users view/modify all results
 * - The owner of a new result is always the authenticated user
 * - dateAndHour is generated by the database (UTC)
 * - Only status and observations can be updated
 * - Results cannot be deleted (audit trail)
 * - Every correction sets the result status to CORRECTED and clears its
 *   verification (verifiedBy / verifiedAt)
 * - A VERIFIED result is locked: no new images, dilution or observation
 *   changes (409 for every role); only an ADMIN may still correct it
 * - Checks that depend on the result status are repeated inside the write
 *   transaction on the row read with an update lock (no race with a
 *   concurrent verification)
 * - Status transitions (PATCH and append): VERIFIED is reached from PENDING or
 *   CORRECTED; CORRECTED only through corrections; nothing returns to PENDING;
 *   keeping the current status is a no-op. Anything else is a 409
 * - Moving a result to VERIFIED records who verified it and when
 *   (verifiedBy / verifiedAt)
 * - Saved predictions must carry the signature returned by
 *   POST /predictions/analyze for the same image (trusted predictions)
 * - A result holds at most MAX_IMAGES_PER_RESULT (20) images, saved ones
 *   included; the append endpoint checks it before storing files and again
 *   under the update lock
 * - Multi-row writes run in one database transaction; stored image files are
 *   removed again when the transaction fails
 * - Audit records are written after the transaction commits (best effort); an
 *   append request that changes nothing writes none
 */

