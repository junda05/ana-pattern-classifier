/** Result columns written by any correction: CORRECTED, verification cleared. */
const CORRECTED_UNVERIFIED: Pick<
  Result,
  'status' | 'verifiedBy' | 'verifiedAt'
> = {
  status: ResultStatus.CORRECTED,
  verifiedBy: null,
  verifiedAt: null,
};

/** Stored text, where '' / null / undefined all mean "no text". */
function sameText(
  a: string | null | undefined,
  b: string | null | undefined,
): boolean {
  return (a || null) === (b || null);
}

/** Current class of a prediction: its latest correction, else the model class. */
function effectiveClass(prediction: Prediction): PredictionClass {
  return (
    latestCorrection<CorrectedResult>(prediction.corrections)
      ?.correctedPrediction ?? prediction.prediction
  );
}

/** STANDARD users may act on their own results and on any PENDING result. */
function canStandardUserAccess(
  result: { userId: number; status: ResultStatus },
  userId?: number,
): boolean {
  return result.userId === userId || result.status === ResultStatus.PENDING;
}

/**
 * Status changes a client may request (PATCH and append). Keeping the current
 * status is always allowed (no-op).
 */
const ALLOWED_STATUS_TRANSITIONS: Record<
  ResultStatus,
  readonly ResultStatus[]
> = {
  [ResultStatus.PENDING]: [ResultStatus.VERIFIED],
  [ResultStatus.CORRECTED]: [ResultStatus.VERIFIED],
  [ResultStatus.VERIFIED]: [],
};

/** @throws ConflictException when `to` cannot be requested from `from` */
function assertStatusTransition(from: ResultStatus, to: ResultStatus): void {
  if (from !== to && !ALLOWED_STATUS_TRANSITIONS[from].includes(to)) {
    throw new ConflictException(
      `Invalid status transition from ${from} to ${to}.`,
    );
  }
}

function assertOnePredictionPerImage(
  imageCount: number,
  predictionCount: number,
): void {
  if (imageCount !== predictionCount) {
    throw new BadRequestException(
      `Each uploaded image needs exactly one prediction (received ${imageCount} images and ${predictionCount} predictions).`,
    );
  }
}

/** @throws BadRequestException when new images would exceed MAX_IMAGES_PER_RESULT */
function assertImageCap(savedImages: number, newImages: number): void {
  if (newImages > 0 && savedImages + newImages > MAX_IMAGES_PER_RESULT) {
    throw new BadRequestException(TOO_MANY_IMAGES);
  }
}

function assertCorrectionIndexes(
  corrections: IndexedCorrectionDto[],
  imageCount: number,
): void {
  corrections.forEach((correction, position) => {
    if (correction.imageIndex >= imageCount) {
      throw new BadRequestException(
        `Correction ${position + 1} refers to image index ${correction.imageIndex}, but only ${imageCount} images were uploaded.`,
      );
    }
  });
  const indexes = corrections.map((correction) => correction.imageIndex);
  if (new Set(indexes).size !== indexes.length) {
    throw new BadRequestException(
      'Each image can be corrected at most once per request.',
    );
  }
}

/** Patient fields copied into result audit records. */
function patientSnapshot(patient: Patient | undefined) {
  return {
    patientId: patient?.patientId,
    patientFullName: patient?.fullName,
    patientDocumentType: patient?.documentType,
    patientDocumentNumber: patient?.documentNumber,
    patientGender: patient?.gender,
    patientBirthDate: patient?.birthDate,
    patientEmail: patient?.email,
    patientPhonePrefix: patient?.phonePrefix,
    patientPhoneNumber: patient?.phoneNumber,
  };
}

/** Prediction as stored in audit records (with its current correction, if any). */
function predictionAuditInfo(prediction: Prediction) {
  const correction = latestCorrection<CorrectedResult>(prediction.corrections);
  return {
    predictionId: prediction.predictionId,
    prediction: prediction.prediction,
    confidencePercentage: prediction.confidencePercentage,
    imagePath: prediction.imagePath,
    imageUrl: predictionImageUrl(prediction.imagePath),
    dilution: prediction.dilution,
    correction: correction
      ? {
          correctedPrediction: correction.correctedPrediction,
          observations: correction.observations,
          correctedDate: correction.correctedDate,
        }
      : undefined,
  };
}

